# Self-check
# ==========================================================================
# Duplicates inside a pool silently shrink it and defeat the no-repeat history,
# so they are worth catching now rather than after a month of output.
POOLS = {
    "TOPIC_POOL": TOPIC_POOL,
    "HOOK_CANDIDATES": HOOK_CANDIDATES,
    "SCREEN_GENERIC": SCREEN_GENERIC,
    "SCREEN_HOOKS": SCREEN_HOOKS,
    "FLASH_GENERIC": FLASH_GENERIC,
    "FLASH_PHRASES": FLASH_PHRASES,
    "CTA_CANDIDATES": CTA_CANDIDATES,
    "DEFAULT_KEYWORDS": DEFAULT_KEYWORDS,
}


def audit():
    """Return {pool_name: (size, [duplicate_keys])} for every pool."""
    report = {}
    for name, pool in POOLS.items():
        seen = set()
        dupes = []
        for item in pool:
            key = item[0] if isinstance(item, tuple) else item
            if key in seen:
                dupes.append(key)
            seen.add(key)
        report[name] = (len(pool), dupes)
    return report


if __name__ == "__main__":
    bad = 0
    for name, (size, dupes) in sorted(audit().items()):
        bad += len(dupes)
        print("%-18s %4d  %s" % (name, size, "OK" if not dupes else "DUPES:%d" % len(dupes)))
        for d in dupes:
            print("      dup: %s" % d)
    print("\ncoverage at 5 reels/day:")
    print("  topics     %5.1f days" % (len(TOPIC_POOL) / 5.0))

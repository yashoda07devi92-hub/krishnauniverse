# WHY THIS EXISTS ALONGSIDE TOPIC_POOL
# ------------------------------------
# TOPIC_POOL is organised around the LEELA - "Krishna lifted Govardhan", "Kaliya
# was defeated". Told that way, a reel is a retelling: the viewer already knows
# the story, so there is nothing to stay for and nothing to take away. The
# channel's own numbers said so (1-9 views per upload).
#
# This pool is organised the other way round: around the SEEKH. Each entry is a
# small moment in which Kanha explains one practical rule of life, plus the
# everyday situation that rule applies to TODAY. The narration is then written as
# a 30-second micro-story that lands a cause-and-effect the viewer can use before
# they finish scrolling - "do this, and this is what happens".
#
# ENTRY FORMAT: (prasang, seekh, jeevan)
#   prasang - the tiny scene to narrate. WHO asks Kanha, and WHAT the moment is.
#             Deliberately small: one question, one answer, one image. A 30-second
#             reel cannot carry a plot AND a lesson, so the plot is kept to two
#             sentences and the lesson gets the rest.
#   seekh   - the takeaway, phrased as cause -> effect, not as an abstract virtue.
#             "Anger is bad" teaches nobody anything; "anger burns the one holding
#             it first" tells them what happens if they keep holding it.
#   jeevan  - where a 2026 viewer meets this exact situation. Passed to the model
#             so the closing line is about the viewer's life, not about Dwarka.
#             This is the field that decides whether someone's day changes.
#
# All three are handed to Gemini explicitly. Left to itself, a "Krishna story
# with a moral" prompt drifts into generic devotional advice that fits any video,
# which is precisely the sameness this channel is trying to escape.
#
# SIZE: 143 entries, every prasang / seekh / jeevan line distinct (checked by
# repeat_audit.py). Mixed with TOPIC_POOL's 150 leelas that is 293 distinct
# premises, and the seekh-fingerprint guard in modules/history.py rejects a
# repeated lesson LINE even after a pool resets - so nothing a viewer can notice
# comes back, ever.
